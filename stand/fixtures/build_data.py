"""Convert the archived synthetic inputs of the two source projects into stand fixtures.

The stand does not run this script: its output is committed next to it, and
stand/fixtures/SOURCES.json records the source commits and every checksum.
Run it again only to regenerate the fixtures from the same inputs:

    python stand/fixtures/build_data.py --orders <orders inputs.json> \
        --marketing <marketing inputs.json>

The orders file is docs/runs/2026-10-31-synthetic/inputs.json of the order picking
project; the marketing file is the same path in the marketing funnel project.
The field mapping repeats that project's loader (scripts/load_clickhouse.py).
"""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ORDER_COLUMNS = (
    "order_id",
    "branch",
    "picker",
    "created_at",
    "started_at",
    "finished_at",
    "status",
    "requested",
    "picked",
    "errors",
)


def sql_literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        raise ValueError("boolean values are not expected in the orders")
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    raise ValueError(f"unsupported value: {value!r}")


def orders_sql(orders):
    lines = [
        "-- Generated by stand/fixtures/build_data.py from the archived synthetic orders.",
        "INSERT INTO picking.orders (" + ", ".join(ORDER_COLUMNS) + ") VALUES",
    ]
    rows = [
        "    (" + ", ".join(sql_literal(order.get(c)) for c in ORDER_COLUMNS) + ")"
        for order in orders
    ]
    if not rows:
        raise ValueError("no orders in the input")
    return "\n".join(lines) + "\n" + ",\n".join(rows) + ";\n"


def utc_text(value):
    moment = datetime.fromisoformat(value)
    if moment.tzinfo is None:
        raise ValueError(f"timestamp without a time zone: {value}")
    return moment.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f")


def marketing_rows(data):
    events = []
    for event in data["events"]:
        moment = datetime.fromisoformat(event["timestamp"]).astimezone(timezone.utc)
        events.append(
            (
                moment,
                event["event_id"],
                {
                    "event_id": event["event_id"],
                    "user_id": event["user_id"],
                    "at": utc_text(event["timestamp"]),
                    "name": event["name"],
                    "channel": event.get("channel") or "",
                    "campaign": event.get("campaign") or "",
                    "revenue_cents": event.get("revenue_cents", 0),
                    "cost_cents": event.get("cost_cents", 0),
                },
            )
        )
    events.sort(key=lambda item: (item[0], item[1]))
    spend = [
        {"channel": row["channel"], "spend_cents": row["spend_cents"]}
        for row in data["spend"]
    ]
    return [row for _, _, row in events], spend


def json_lines(rows):
    return "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows)


def build(orders_path, marketing_path, out=HERE):
    orders = json.loads(Path(orders_path).read_text(encoding="utf-8"))["orders"]
    marketing = json.loads(Path(marketing_path).read_text(encoding="utf-8"))
    events, spend = marketing_rows(marketing)
    outputs = {
        out / "postgres" / "orders_data.sql": orders_sql(orders),
        out / "clickhouse" / "events.jsonl": json_lines(events),
        out / "clickhouse" / "spend.jsonl": json_lines(spend),
    }
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return {"orders": len(orders), "events": len(events), "spend": len(spend)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--orders", type=Path, required=True)
    parser.add_argument("--marketing", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(build(args.orders, args.marketing)))


if __name__ == "__main__":
    main()
